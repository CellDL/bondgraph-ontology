"""Assemble the GitHub Pages site under site/.

The site is what https://w3id.org/bondgraph/* resolves to for the current version of
each module. It holds, for every module:

  bondgraph-<name>.ttl      a verbatim copy of the hand-authored Turtle, comments and
                            all -- not a reserialisation, which would discard them
  bondgraph-<name>.rdf      RDF/XML     \\
  bondgraph-<name>.jsonld   JSON-LD      > generated by build_serialisations.py
  bondgraph-<name>.nt       N-Triples   /

plus an index.html, which is the target a browser gets.

Run build_serialisations.py first; this copies what that produced.

Usage:  python scripts/build_site.py
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
SITE = ROOT / "site"

MODULES = {
    "bondgraph-core": (ROOT / "src/bondgraph-core.ttl", "Core", "The bond graph formalism itself."),
    "bondgraph-bfo": (ROOT / "src/bondgraph-bfo.ttl", "BFO bridge",
                      "Pins the ontology to the Basic Formal Ontology, via IAO and RO."),
    "bondgraph-biochem": (ROOT / "src/domains/bondgraph-biochem.ttl", "Biochemical domain",
                          "Species and reaction components, chemostats, transducers."),
    "bondgraph-hydraulic": (ROOT / "src/domains/bondgraph-hydraulic.ttl", "Hydraulic domain",
                            "Vessel compliance, fluid inertia, laminar and turbulent resistance, valves."),
    "bondgraph-thermal": (ROOT / "src/domains/bondgraph-thermal.ttl", "Thermal domain",
                          "Entropy-based thermal capacitance, and the two cases of the RS element."),
}
EXTS = ("ttl", "rdf", "jsonld", "nt")

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Bond Graph Ontology</title>
<style>
 body {{ font-family: system-ui, sans-serif; max-width: 48rem; margin: 3rem auto;
        padding: 0 1rem; line-height: 1.5; }}
 table {{ border-collapse: collapse; width: 100%; margin: 1.5rem 0; }}
 th, td {{ text-align: left; padding: 0.4rem 0.6rem; border-bottom: 1px solid #ddd;
          vertical-align: top; }}
 code {{ background: #f4f4f4; padding: 0.1rem 0.3rem; }}
 .sub {{ color: #555; font-size: 0.9rem; }}
</style>
</head>
<body>
<h1>Bond Graph Ontology</h1>
<p>An OWL 2 DL axiomatisation of the bond graph formalism, used for describing
physiological processes. Source and documentation:
<a href="https://github.com/CellDL/bondgraph-ontology">CellDL/bondgraph-ontology</a>.</p>
<p>Each module below is published in four syntaxes. The Turtle is the authored source
and carries the comments explaining the axioms; the others are generated from it and
checked isomorphic to it on every build.</p>
<table>
<tr><th>Module</th><th>IRI</th><th>Syntaxes</th></tr>
{rows}
</table>
<p class="sub">Ontology licensed under
<a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>; tooling under
Apache-2.0. Version IRIs such as <code>https://w3id.org/bondgraph/core/0.1.0</code>
resolve to the Turtle at the matching git tag.</p>
</body>
</html>
"""


def main():
    if SITE.exists():
        shutil.rmtree(SITE)
    SITE.mkdir()
    (SITE / ".nojekyll").write_text("")
    missing, rows = [], []
    for name, (src, label, blurb) in MODULES.items():
        if not src.exists():
            missing.append(str(src))
            continue
        shutil.copyfile(src, SITE / f"{name}.ttl")
        for ext in ("rdf", "jsonld", "nt"):
            gen = DIST / f"{name}.{ext}"
            if gen.exists():
                shutil.copyfile(gen, SITE / f"{name}.{ext}")
            else:
                missing.append(str(gen))
        iri = "https://w3id.org/bondgraph/" + name.replace("bondgraph-", "")
        links = " · ".join(f'<a href="{name}.{e}">{e}</a>' for e in EXTS)
        rows.append(f'<tr><td><strong>{label}</strong><br><span class="sub">{blurb}</span></td>'
                    f'<td><code>{iri}</code></td><td>{links}</td></tr>')
    (SITE / "index.html").write_text(PAGE.format(rows="\n".join(rows)))

    files = sorted(p.name for p in SITE.iterdir())
    print(f"site/: {len(files)} files")
    print("  " + ", ".join(files))
    if missing:
        print("MISSING inputs:\n  " + "\n  ".join(missing))
    expected = 1 + 1 + len(MODULES) * len(EXTS)   # .nojekyll + index.html + per-module
    if len(files) != expected:
        print(f"expected {expected} files, found {len(files)}")
    return len(missing) or (len(files) != expected)


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
